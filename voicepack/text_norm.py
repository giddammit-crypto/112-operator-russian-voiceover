# Латиница, которая иначе будет прочитана с английским акцентом.
LATIN_FIXES = {
    r"\bOK\b": "хорошо",
    r"\bok\b": "хорошо",
    r"\bSOS\b": "эс-о-эс",
    r"\bGPS\b": "джи-пи-эс",
    r"\bSMS\b": "эс-эм-эс",
    r"\bTV\b": "тэ-вэ",
    r"\bWC\b": "туалет",
    r"\bpolice\b": "полиция",
    r"\b911\b": "девять один один",
}

SCREEN_TAG_RE = re.compile(r"^\s*\{([^}]*)\}\s*")
TIMING_RE = re.compile(r"\[\[\s*[\d.]+\s*\]\]")
PLACEHOLDER_RE = re.compile(r"\[\[\s*([A-Z_]+)\s*\]\]")
HTML_RE = re.compile(r"</?[a-zA-Z][^>]*>")
PAREN_REMARK_RE = re.compile(r"\((?:[^()]{0,60})\)")

PLACEHOLDERS = {
    "ADDRESS": "по этому адресу",
    "STREET": "на этой улице",
    "DISTRICT": "в нашем районе",
    "CITY": "в городе",
    "NAME": "",
    "TIME": "только что",
    "PHONE": "по этому номеру",
    "NUMBER": "номер",
}


def split_screen_tag(text: str) -> tuple[str, str]:
    """
    Отделить экранный тег вида {ЧТО СЛУЧИЛОСЬ?} от произносимой реплики.

    В игре в фигурных скобках стоит короткая подпись на кнопке выбора, а после
    неё — то, что оператор произносит вслух. Озвучивать нужно только второе.
    Если после тега ничего нет — озвучиваем сам тег (это и есть реплика).
    """
    m = SCREEN_TAG_RE.match(text or "")
    if not m:
        return "", (text or "").strip()
    tag = m.group(1).strip()
    rest = text[m.end():].strip()
    if rest:
        return tag, rest
    return tag, tag


def _expand_numbers(text: str) -> str:
    # Время 14:30
    def time_repl(m):
        h, mi = int(m.group(1)), int(m.group(2))
        if mi == 0:
            return f"{number_to_words(h)} часов ровно"
        return f"{number_to_words(h)} {_plural(h, ('час', 'часа', 'часов'))} " \
               f"{number_to_words(mi, feminine=True)} {_plural(mi, ('минута', 'минуты', 'минут'))}"
    text = re.sub(r"\b(\d{1,2}):(\d{2})\b", time_repl, text)

    # Температура -15°C
    def temp_repl(m):
        sign = "минус " if m.group(1) == "-" else ""
        v = int(m.group(2))
        return f"{sign}{number_to_words(v)} {_plural(v, ('градус', 'градуса', 'градусов'))}"
    text = re.sub(r"([+-]?)(\d{1,3})\s*°\s*[CСc]?", temp_repl, text)

    # Проценты
    text = re.sub(r"\b(\d+)\s*%", lambda m: f"{number_to_words(int(m.group(1)))} процентов", text)

    # Порядковые: 5-й, 3-я, 2-е
    text = re.sub(r"\b(\d+)-(?:й|я|е|го|му|ой|ые|ый)\b",
                  lambda m: ordinal_to_words(int(m.group(1))), text)

    # Номер 112 — самое важное для этой игры
    text = re.sub(r"\b112\b", "сто двенадцать", text)
    text = re.sub(r"\b101\b", "сто один", text)
    text = re.sub(r"\b102\b", "сто два", text)
    text = re.sub(r"\b103\b", "сто три", text)
    text = re.sub(r"\b104\b", "сто четыре", text)

    # Диапазоны 5-10
    text = re.sub(r"\b(\d+)\s*-\s*(\d+)\b",
                  lambda m: f"{number_to_words(int(m.group(1)))} — "
                            f"{number_to_words(int(m.group(2)))}", text)

    # Десятичные 2.5 / 2,5
    text = re.sub(r"\b(\d+)[.,](\d+)\b",
                  lambda m: f"{number_to_words(int(m.group(1)))} целых "
                            f"{number_to_words(int(m.group(2)))}", text)

    # Остальные целые числа
    text = re.sub(r"\b\d+\b", lambda m: number_to_words(int(m.group(0))), text)
    return text


def normalize_for_speech(text: str, expand_numbers: bool = True) -> str:
    """Привести реплику к виду, пригодному для естественного русского синтеза."""
    if not text:
        return ""

    t = text

    # 1. Разметка движка
    t = HTML_RE.sub(" ", t)
    t = TIMING_RE.sub(" ", t)
    t = PLACEHOLDER_RE.sub(lambda m: PLACEHOLDERS.get(m.group(1), " "), t)
    t = t.replace("{", " ").replace("}", " ")

    # 2. Ремарки в скобках — не произносятся
    t = PAREN_REMARK_RE.sub(" ", t)

    # 3. Ё восстанавливаем в частых словах — без неё интонация «плывёт»
    for a, b in (("все же", "всё же"), ("еще", "ещё"), ("нашел", "нашёл"),
                 ("пришел", "пришёл"), ("идет", "идёт"), ("несет", "несёт"),
                 ("зовет", "зовёт"), ("падет", "падёт"), ("живет", "живёт")):
        t = re.sub(rf"\b{a}\b", b, t)

    # 4. Аббревиатуры и латиница
    for pat, rep in LATIN_FIXES.items():
        t = re.sub(pat, rep, t)
    for acr, rep in ACRONYMS.items():
        t = re.sub(rf"\b{acr}\b", rep, t)
    for pat, rep in PREPOSITION_CASES:
        t = re.sub(pat, rep, t, flags=re.IGNORECASE)
    for pat, rep in ABBREVIATIONS:
        t = re.sub(pat, rep, t, flags=re.IGNORECASE)

    # 5. Числа
    if expand_numbers:
        t = _expand_numbers(t)

    # 6. Пунктуация → дыхание
    t = t.replace("…", "...")
    t = re.sub(r"\.{3,}", "... ", t)        # длинная пауза
    t = re.sub(r"!{2,}", "!", t)            # «!!!» звучит одинаково с «!»
    t = re.sub(r"\?{2,}", "?", t)
    t = re.sub(r"[—–]\s*", " — ", t)
    t = t.replace("«", '"').replace("»", '"')

    # 7. Остатки латиницы транслитерируем, чтобы не было акцента
    t = _translit_leftovers(t)

    # 8. Пробелы
    t = re.sub(r"\s+", " ", t).strip()
    t = re.sub(r"\s+([,.!?;:])", r"\1", t)

    # 9. Заглавная в начале фразы — влияет на интонацию у нейронных движков
    if t and t[0].islower():
        t = t[0].upper() + t[1:]
    return t


_TRANSLIT = {
    "a": "а", "b": "б", "c": "к", "d": "д", "e": "е", "f": "ф", "g": "г",
    "h": "х", "i": "и", "j": "дж", "k": "к", "l": "л", "m": "м", "n": "н",
    "o": "о", "p": "п", "q": "к", "r": "р", "s": "с", "t": "т", "u": "у",
    "v": "в", "w": "в", "x": "кс", "y": "й", "z": "з",
}


def _translit_leftovers(text: str) -> str:
    """Транслитерировать оставшиеся латинские слова — убирает акцент у TTS."""
    def repl(m):
        word = m.group(0)
        return "".join(_TRANSLIT.get(ch.lower(), ch) for ch in word)
    return re.sub(r"\b[A-Za-z]{2,}\b", repl, text)
