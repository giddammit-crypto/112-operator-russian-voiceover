# Падежные формы адресных сокращений: «на ул. Ленина» должно звучать
# «на улице Ленина», а не «на улица Ленина» — иначе сразу слышен робот.
PREPOSITION_CASES = [
    (r"\b(на|по|о|об|при)\s+ул\.\s*", r"\1 улице "),
    (r"\b(с|со|до|от|у|возле|около|вдоль)\s+ул\.\s*", r"\1 улицы "),
    (r"\b(на|по|о|об|при)\s+пр-?кт\.\s*", r"\1 проспекте "),
    (r"\b(на|по|о|об|при)\s+наб\.\s*", r"\1 набережной "),
    (r"\b(на|по|о|об|при)\s+ш\.\s*", r"\1 шоссе "),
    (r"\b(в|на|о|об|при)\s+пер\.\s*", r"\1 переулке "),
    (r"\b(в|на|о|об|при)\s+д\.\s*(?=\d)", r"\1 доме "),
    (r"\b(в|на|о|об|при)\s+кв\.\s*(?=\d)", r"\1 квартире "),
    (r"\b(в|на|о|об|при)\s+г\.\s*(?=[А-ЯЁ])", r"\1 городе "),
]

