"""
Нормализация русского текста перед синтезом.

Зачем это нужно: TTS читает «112», «ул.», «5 л.», «t=-15°C», «№4» либо
неправильно, либо с английским акцентом («one twelve»). Голос сразу
перестаёт звучать по-русски. Здесь текст приводится к тому виду, как его
произнёс бы живой диктор.

Обрабатывается:
  * служебная разметка игры: {ЭКРАННЫЙ ТЕГ}, [[0.5]], [[ADDRESS]], <b>...</b>;
  * ремарки в скобках, которые не произносятся;
  * числа (количественные и порядковые), проценты, время, температура;
  * сокращения служб и адресов: ул., д., кв., т.д., МЧС, ДТП, СМП;
  * латиница в русском тексте (иначе движок читает её с акцентом);
  * пунктуация для дыхания: многоточия → короткие паузы, тире, «!!» → «!».
"""

from __future__ import annotations

import re

# ---------------------------------------------------------------------------
# Числа словами
# ---------------------------------------------------------------------------

_ONES_M = ("ноль", "один", "два", "три", "четыре", "пять", "шесть", "семь",
           "восемь", "девять")
_ONES_F = ("ноль", "одна", "две", "три", "четыре", "пять", "шесть", "семь",
           "восемь", "девять")
_TEENS = ("десять", "одиннадцать", "двенадцать", "тринадцать", "четырнадцать",
          "пятнадцать", "шестнадцать", "семнадцать", "восемнадцать", "девятнадцать")
_TENS = ("", "", "двадцать", "тридцать", "сорок", "пятьдесят", "шестьдесят",
         "семьдесят", "восемьдесят", "девяносто")
_HUNDREDS = ("", "сто", "двести", "триста", "четыреста", "пятьсот", "шестьсот",
             "семьсот", "восемьсот", "девятьсот")

_ORDINALS = {
    1: "первый", 2: "второй", 3: "третий", 4: "четвёртый", 5: "пятый",
    6: "шестой", 7: "седьмой", 8: "восьмой", 9: "девятый", 10: "десятый",
    11: "одиннадцатый", 12: "двенадцатый", 13: "тринадцатый", 14: "четырнадцатый",
    15: "пятнадцатый", 16: "шестнадцатый", 17: "семнадцатый", 18: "восемнадцатый",
    19: "девятнадцатый", 20: "двадцатый", 30: "тридцатый", 40: "сороковой",
    50: "пятидесятый", 60: "шестидесятый", 100: "сотый",
}


def _under_thousand(n: int, feminine: bool = False) -> list[str]:
    parts = []
    ones = _ONES_F if feminine else _ONES_M
    if n >= 100:
        parts.append(_HUNDREDS[n // 100])
        n %= 100
    if 10 <= n <= 19:
        parts.append(_TEENS[n - 10])
        return parts
    if n >= 20:
        parts.append(_TENS[n // 10])
        n %= 10
    if n > 0:
        parts.append(ones[n])
    return parts


def _plural(n: int, forms: tuple[str, str, str]) -> str:
    n = abs(n) % 100
    if 11 <= n <= 14:
        return forms[2]
    n %= 10
    if n == 1:
        return forms[0]
    if 2 <= n <= 4:
        return forms[1]
    return forms[2]


def number_to_words(n: int, feminine: bool = False) -> str:
    """Целое число прописью (до миллиардов)."""
    if n == 0:
        return "ноль"
    if n < 0:
        return "минус " + number_to_words(-n, feminine)

    groups = [
        (10 ** 9, ("миллиард", "миллиарда", "миллиардов"), False),
        (10 ** 6, ("миллион", "миллиона", "миллионов"), False),
        (10 ** 3, ("тысяча", "тысячи", "тысяч"), True),
    ]
    words: list[str] = []
    for base, forms, fem in groups:
        if n >= base:
            count = n // base
            n %= base
            words.extend(_under_thousand(count, fem))
            words.append(_plural(count, forms))
    if n > 0:
        words.extend(_under_thousand(n, feminine))
    return " ".join(w for w in words if w)


def ordinal_to_words(n: int) -> str:
    if n in _ORDINALS:
        return _ORDINALS[n]
    if n < 100:
        tens = (n // 10) * 10
        ones = n % 10
        if ones and tens in _ORDINALS:
            return f"{_TENS[tens // 10]} {_ORDINALS.get(ones, str(ones))}"
    return number_to_words(n)


