sem = asyncio.Semaphore(6)

async def synthesize_track(text, voice_key, out_path, is_chatter=False):
    async with sem:
        temp_mp3 = os.path.join(TEMP_DIR, f"tmp_{abs(hash(text + out_path))}.mp3")
        try:
            cfg = VOICES[voice_key] if not is_chatter else {"voice": "ru-RU-DmitryNeural", "pitch": "-6Hz", "rate": "+2%"}
            comm = edge_tts.Communicate(text=text, voice=cfg["voice"], pitch=cfg["pitch"], rate=cfg["rate"], volume="+50%")
            await comm.save(temp_mp3)

            os.makedirs(os.path.dirname(out_path), exist_ok=True)
            
            # Use cinematic radio filter
            cmd = [
                "ffmpeg", "-y",
                "-i", PTT_START,
                "-i", temp_mp3,
                "-i", PTT_END,
                "-filter_complex",
                "[0:a]aresample=44100[a0];[1:a]aresample=44100[a1];[2:a]aresample=44100[a2];"
                "[a0][a1][a2]concat=n=3:v=0:a=1[raw];"
                "[raw]highpass=f=280,lowpass=f=3800,equalizer=f=1200:t=q:w=1.5:g=3,equalizer=f=2800:t=q:w=1.8:g=5,"
                "asoftclip=type=atan,acompressor=threshold=-18dB:ratio=5:attack=5:release=50,volume=2.2,aresample=44100[out]",
                "-map", "[out]", "-ac", "2", "-ar", "44100",
                out_path
            ]
            res = subprocess.run(cmd, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
            if res.returncode != 0:
                print("FFmpeg error on", out_path)
        except Exception as ex:
            print(f"Error synthesizing {out_path}: {ex}")
        finally:
            if os.path.exists(temp_mp3):
                os.remove(temp_mp3)

async def main():
    print("=== STARTING CINEMATIC RUSSIAN RADIO GENERATION (371 FILES) ===")
    tasks = []
    
    # 1. Generate Unit Radio messages
    for cat, data in SCRIPTS.items():
        for voice_key in ["Male1", "Male2", "Female1", "Female2"]:
            lines = data.get(voice_key, [])
            folder = os.path.join(DEST_ROOT, VOICES[voice_key]["folder"])
            for idx, text in enumerate(lines):
                suffix = f"_{idx+1}" if len(lines) > 1 else ""
                filename = f"{cat}{suffix}.wav"
                out_path = os.path.join(folder, filename)
                tasks.append(synthesize_track(text, voice_key, out_path))

    # 2. Generate Chatter
    chatter_folder = os.path.join(DEST_ROOT, "Chatter")
    for idx, text in enumerate(CHATTER_SCRIPTS):
        filename = f"chatter_{idx+1}.wav"
        out_path = os.path.join(chatter_folder, filename)
        tasks.append(synthesize_track(text, "Male1", out_path, is_chatter=True))

    print(f"Total tracks to synthesize: {len(tasks)}")
    await asyncio.gather(*tasks)
    print("=== CINEMATIC RADIO PACK GENERATION COMPLETED! ===")

if __name__ == "__main__":
    asyncio.run(main())
