import uuid

async def process_item(semaphore, text, voice, pitch, rate, out_wav, temp_dir):
    async with semaphore:
        unique_id = uuid.uuid4().hex
        base_name = os.path.splitext(os.path.basename(out_wav))[0]
        temp_mp3 = os.path.join(temp_dir, f"{base_name}_{unique_id}.mp3")
        try:
            comm = edge_tts.Communicate(text, voice, pitch=pitch, rate=rate)
            await comm.save(temp_mp3)
            
            cmd = [
                "ffmpeg", "-y", "-i", temp_mp3,
                "-af", "highpass=f=350,lowpass=f=3300,volume=1.8,asoftclip=type=atan,acompressor=threshold=-15dB:ratio=5:attack=5:release=50,highpass=f=400,lowpass=f=3200",
                "-ar", "44100", "-ac", "2",
                out_wav
            ]
            res = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
            if res.returncode != 0:
                print(f"FFmpeg error on {out_wav}: {res.stderr.decode()}")
        except Exception as e:
            print(f"Error generating {out_wav}: {e}")
        finally:
            if os.path.exists(temp_mp3):
                try:
                    os.remove(temp_mp3)
                except Exception:
                    pass

